import assert from 'node:assert/strict';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const EXPECTED_REFERENCE_SNIPPETS = Object.freeze([
  'application-signals',
  'operation-decisions',
  'controlled-form-template',
]);

export const EXPECTED_STANDARD_REFERENCE_SNIPPETS = Object.freeze([
  'standard-compile-definition',
  'standard-create-runtime',
  'standard-runtime-subscriptions',
  'standard-controlled-operation',
  'standard-runtime-cleanup',
]);

const DEFAULT_SOURCE =
  'apps/reference-angular/src/app/reference-form.component.ts';
const DEFAULT_OUTPUT =
  'apps/reference-angular/src/app/generated/reference-snippets.ts';
export const REFERENCE_SNIPPET_TARGETS = Object.freeze([
  Object.freeze({
    id: 'angular',
    sourcePath: DEFAULT_SOURCE,
    outputPath: DEFAULT_OUTPUT,
    expectedIds: EXPECTED_REFERENCE_SNIPPETS,
  }),
  Object.freeze({
    id: 'standard',
    sourcePath: 'apps/reference-standard/src/reference-application.ts',
    outputPath: 'apps/reference-standard/src/generated/reference-snippets.ts',
    expectedIds: EXPECTED_STANDARD_REFERENCE_SNIPPETS,
  }),
]);
const TYPESCRIPT_MARKER =
  /^\s*\/\/ reference-snippet:(start|end) ([a-z0-9]+(?:-[a-z0-9]+)*)\s*$/u;
const TEMPLATE_MARKER =
  /^\s*<!-- reference-snippet:(start|end) ([a-z0-9]+(?:-[a-z0-9]+)*) -->\s*$/u;

function marker(line) {
  return TYPESCRIPT_MARKER.exec(line) ?? TEMPLATE_MARKER.exec(line);
}

function normalizeLines(source) {
  return source.replaceAll('\r\n', '\n').replaceAll('\r', '\n').split('\n');
}

function trimIndent(lines) {
  const copy = [...lines];
  while (copy[0]?.trim() === '') copy.shift();
  while (copy.at(-1)?.trim() === '') copy.pop();
  if (copy.length === 0) return '';
  const indentation = Math.min(
    ...copy
      .filter((line) => line.trim().length > 0)
      .map((line) => /^\s*/u.exec(line)?.[0].length ?? 0),
  );
  return copy.map((line) => line.slice(indentation)).join('\n');
}

export function extractReferenceSnippets(
  source,
  expectedIds = EXPECTED_REFERENCE_SNIPPETS,
) {
  const expected = new Set(expectedIds);
  const snippets = new Map();
  let active;

  for (const [index, line] of normalizeLines(source).entries()) {
    const match = marker(line);
    if (match === null) {
      if (active !== undefined) active.lines.push(line);
      continue;
    }
    const [, kind, id] = match;
    assert.equal(expected.has(id), true, `Unexpected snippet marker: ${id}`);
    if (kind === 'start') {
      assert.equal(active, undefined, `Nested snippet marker: ${id}`);
      assert.equal(snippets.has(id), false, `Duplicate snippet marker: ${id}`);
      active = { id, line: index + 1, lines: [] };
      continue;
    }
    assert.notEqual(active, undefined, `Unmatched snippet end: ${id}`);
    assert.equal(active.id, id, `Mismatched snippet end: ${id}`);
    const value = trimIndent(active.lines);
    assert.notEqual(value, '', `Empty snippet: ${id}`);
    snippets.set(id, value);
    active = undefined;
  }

  assert.equal(
    active,
    undefined,
    `Unclosed snippet marker: ${active?.id ?? '<unknown>'}`,
  );
  for (const id of expectedIds) {
    assert.equal(snippets.has(id), true, `Missing snippet marker: ${id}`);
  }
  return Object.freeze(
    Object.fromEntries(expectedIds.map((id) => [id, snippets.get(id)])),
  );
}

function quote(value) {
  const delimiter =
    value.split("'").length > value.split('"').length ? '"' : "'";
  return `${delimiter}${value
    .replaceAll('\\', '\\\\')
    .replaceAll(delimiter, `\\${delimiter}`)
    .replaceAll('\u2028', '\\u2028')
    .replaceAll('\u2029', '\\u2029')}${delimiter}`;
}

export function renderReferenceSnippets(
  snippets,
  expectedIds = EXPECTED_REFERENCE_SNIPPETS,
) {
  const output = [
    '// Generated by scripts/extract-reference-snippets.mjs. Do not edit.',
    '',
    'export const referenceSnippets = Object.freeze({',
  ];
  for (const id of expectedIds) {
    const value = snippets[id];
    assert.equal(typeof value, 'string', `Missing rendered snippet: ${id}`);
    output.push(`  ${quote(id)}: [`);
    for (const line of value.split('\n')) output.push(`    ${quote(line)},`);
    output.push("  ].join('\\n'),");
  }
  output.push(
    '});',
    '',
    'export type ReferenceSnippetId = keyof typeof referenceSnippets;',
    '',
  );
  return output.join('\n');
}

export function runReferenceSnippetExtraction({
  mode,
  sourcePath = DEFAULT_SOURCE,
  outputPath = DEFAULT_OUTPUT,
  expectedIds = EXPECTED_REFERENCE_SNIPPETS,
  root = resolve('.'),
}) {
  assert.equal(
    mode === 'write' || mode === 'check',
    true,
    'Snippet mode must be write or check.',
  );
  const source = readFileSync(resolve(root, sourcePath), 'utf8');
  const expected = renderReferenceSnippets(
    extractReferenceSnippets(source, expectedIds),
    expectedIds,
  );
  const target = resolve(root, outputPath);
  if (mode === 'write') {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, expected);
    return Object.freeze({ changed: true, snippets: expectedIds.length });
  }
  assert.equal(
    existsSync(target),
    true,
    `Missing generated snippets: ${outputPath}`,
  );
  assert.equal(
    readFileSync(target, 'utf8'),
    expected,
    `Stale generated snippets: ${outputPath}`,
  );
  return Object.freeze({ changed: false, snippets: expectedIds.length });
}

export function runReferenceSnippetTargets({
  mode,
  root = resolve('.'),
  targets = REFERENCE_SNIPPET_TARGETS,
}) {
  const results = targets.map((target) =>
    runReferenceSnippetExtraction({ mode, root, ...target }),
  );
  return Object.freeze({
    changed: results.some(({ changed }) => changed),
    snippets: results.reduce((total, result) => total + result.snippets, 0),
    targets: results.length,
  });
}

const currentFile = fileURLToPath(import.meta.url);
if (
  process.argv[1] !== undefined &&
  pathToFileURL(resolve(process.argv[1])).href ===
    pathToFileURL(currentFile).href
) {
  const mode = process.argv.includes('--write')
    ? 'write'
    : process.argv.includes('--check')
      ? 'check'
      : undefined;
  try {
    assert.notEqual(mode, undefined, 'Use exactly --write or --check.');
    assert.equal(
      process.argv.includes('--write') && process.argv.includes('--check'),
      false,
      'Use exactly --write or --check.',
    );
    const result = runReferenceSnippetTargets({ mode });
    console.log(
      `${mode === 'write' ? 'Generated' : 'Verified'} ${result.snippets} reference snippets across ${result.targets} targets.`,
    );
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
